class Book {
  final String id;
  final String title;
  final String author;
  final String image;
  final double price;
  final int totalPages;
  final String category;
  final String description;

  Book({
    required this.id,
    required this.title,
    required this.author,
    required this.image,
    required this.price,
    required this.totalPages,
    required this.category,
    required this.description,
  });
}