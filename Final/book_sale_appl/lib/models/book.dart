class Book {
  final String id;
  final String title;
  final String description;
  final String category;
  final String coverUrl;
  final int pages;
  final double price;

  Book({
    required this.id,
    required this.title,
    required this.description,
    required this.category,
    required this.coverUrl,
    required this.pages,
    required this.price,
  });
}
