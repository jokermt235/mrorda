class Book {
  final String id;
  final String title;
  final String author; 
  final double price;
  final String category;
  final int pageCount;
  final String coverImage;

  Book({
    required this.id,
    required this.title,
    required this.author, 
    required this.price,
    required this.category,
    required this.pageCount,
    required this.coverImage,
  });
}
